def numero_a_cadena(n):
    """
    Convierte un número entero en una cadena de texto.

    Args:
        n (int): Número entero a convertir (puede ser negativo).

    Returns:
        str: Representación del número como cadena.

    Example:
        numero_a_cadena(-100)
        '-100'
    """
    #transforma un numero en String
    return str(n)

print(numero_a_cadena(123))
